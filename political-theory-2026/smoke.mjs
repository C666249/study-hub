import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser=await chromium.launch({headless:true});
const errors=[];
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
page.on('pageerror',e=>errors.push(String(e)));
page.on('dialog',d=>d.accept());
const base='http://127.0.0.1:8765/political-theory-2026/';
try{
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('.topic-card').first().waitFor();
 assert.equal(await page.locator('.topic-card').count(),7,'seven knowledge topics');
 assert.match(await page.locator('body').innerText(),/60/,'full bank count visible');
 await page.locator('#mobileNav a[href="#quiz/all"]').click();
 await page.locator('.question-title').waitFor();
 assert.match(await page.locator('.step-counter').innerText(),/1 \/ 60/);
 const footer=await page.locator('.quiz-bottom').evaluate(el=>({style:getComputedStyle(el).position,bottom:el.getBoundingClientRect().bottom,win:innerHeight}));
 assert.equal(footer.style,'fixed','bottom actions should stay fixed');
 assert.ok(Math.abs(footer.bottom-footer.win)<3,'bottom actions anchored to viewport');
 await page.locator('.answer').nth(1).click();
 assert.match(await page.locator('.explanation').innerText(),/回答正确/);
 await page.locator('[data-action="next"]').click();
 assert.match(await page.locator('.step-counter').innerText(),/2 \/ 60/);
 await page.reload({waitUntil:'networkidle'});
 assert.match(await page.locator('.step-counter').innerText(),/2 \/ 60/,'full bank session must persist');
 await page.locator('[data-action="prev"]').click();
 assert.match(await page.locator('.explanation').innerText(),/回答正确/,'answer persists after reload');
 await page.locator('[data-action="route"][data-route="home"]').first().click();
 await page.locator('[data-mode="random"]').first().click();
 assert.match(await page.locator('.step-counter').innerText(),/1 \/ 60/,'random includes all 60');
 await page.locator('[data-action="next"]').click();
 assert.match(await page.locator('.step-counter').innerText(),/2 \/ 60/);
 await page.locator('[data-action="route"][data-route="home"]').first().click();
 await page.locator('#mobileNav a[href="#quiz/all"]').click();
 assert.match(await page.locator('.step-counter').innerText(),/1 \/ 60/,'all-mode progress remains independent');
 await page.locator('[data-action="route"][data-route="home"]').first().click();
 await page.locator('[data-action="route"][data-route="practice"]').first().click();
 await page.locator('.bank-row[data-id="M01"]').first().click();
 assert.match(await page.locator('.question-title').innerText(),/两会/);
 assert.match(await page.locator('.step-counter').innerText(),/41 \/ 60/);
 await page.locator('.answer').first().click();
 await page.locator('.answer').nth(2).click();
 await page.locator('.answer').nth(3).click();
 await page.locator('[data-action="submit-multi"]').click();
 await page.locator('.explanation').waitFor();
 await page.goto(base+'#exam',{waitUntil:'networkidle'});
 await page.locator('[data-action="start-exam"]').click();
 assert.match(await page.locator('.step-counter').innerText(),/1 \/ 30/);
 assert.equal(await page.locator('.quest-panel .answer').count(),4);
 await page.locator('[data-action="route"][data-route="exam"]').click();
 await page.locator('[data-action="start-exam"]').click();
 assert.match(await page.locator('.step-counter').innerText(),/1 \/ 30/,'exam progress survives leave/reentry');
 await page.setViewportSize({width:1380,height:900});
 await page.goto(base,{waitUntil:'networkidle'});
 assert.equal(await page.locator('.sidebar').isVisible(),true,'desktop sidebar visible');
 await page.locator('#desktopNav a[href="#quiz/all"]').click();
 assert.match(await page.locator('.step-counter').innerText(),/41 \/ 60/,'desktop tab resumes all 60');
 assert.deepEqual(errors,[],'no uncaught JavaScript exceptions');
 console.log('Browser smoke passed: 7 topics, full 60, random independence, local persistence, sticky nav, multi-choice, 30-question mock, mobile and desktop navigation');
} finally {await browser.close()}
