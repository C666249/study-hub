import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[];page.on('pageerror',err=>errors.push(String(err)));
page.on('dialog',dlg=>dlg.accept());
const url='http://127.0.0.1:8765/political-theory-2026/';
try{
 await page.goto(url,{waitUntil:'networkidle'});
 await page.locator('.welcome').waitFor();
 assert.equal(await page.locator('.metric').count(),3);
 await page.locator('.nav-item[href="#learn"]').click();
 await page.locator('.topic-item').first().waitFor();
 assert.equal(await page.locator('.topic-item').count(),7);
 await page.locator('.topic-item').first().click();
 await page.locator('.lesson-button').first().waitFor();
 await page.locator('.lesson-button').first().click();
 assert.equal(await page.locator('.lesson-button').first().getAttribute('aria-expanded'),'true');
 await page.locator('.nav-item[href="#practice"]').click();
 await page.locator('details.numbers-wrap summary').waitFor();
 assert.equal(await page.locator('details.numbers-wrap').getAttribute('open'),null,'question directory is collapsed by default');
 await page.locator('details.numbers-wrap summary').click();
 assert.equal(await page.locator('.number-dot').count(),60,'full bank index contains 60');
 await page.locator('.practice-hero [data-act="open-all"]').click();
 await page.locator('.question-title').waitFor();
 assert.match(await page.locator('.dock-mid').innerText(),/1 \/ 60/);
 assert.equal(await page.locator('.option').count(),4);
 const fixed=await page.locator('.focus-dock').evaluate(el=>({pos:getComputedStyle(el).position,bottom:el.getBoundingClientRect().bottom,height:innerHeight}));
 assert.equal(fixed.pos,'fixed');
 assert.ok(Math.abs(fixed.bottom-fixed.height)<3,'quiz navigation must anchor to viewport');
 const font=await page.locator('.option-copy').first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize));
 assert.ok(font>=16,'answer text must stay at least 16px on mobile');
 await page.locator('.option').nth(1).click();
 assert.match(await page.locator('.feedback').innerText(),/已掌握/,'correct option must score as correct');
 await page.locator('[data-act="next"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/2 \/ 60/);
 await page.reload({waitUntil:'networkidle'});
 assert.match(await page.locator('.dock-mid').innerText(),/2 \/ 60/,'session progress persists across reload');
 await page.locator('[data-act="prev"]').click();
 assert.match(await page.locator('.feedback').innerText(),/正确答案 B/);
 await page.locator('[data-act="show-sheet"]').click();
 assert.equal(await page.locator('.sheet .number-dot').count(),60);
 await page.locator('[data-act="sheet-jump"][data-index="40"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/41 \/ 60/);
 assert.match(await page.locator('.question-title').innerText(),/两会/);
 await page.locator('.option').nth(0).click();
 await page.locator('.option').nth(2).click();
 await page.locator('.option').nth(3).click();
 await page.locator('[data-act="submit"]').click();
 assert.match(await page.locator('.feedback').innerText(),/正确答案 ACD/);
 await page.locator('[data-act="go-practice"]').click();
 await page.locator('.practice-hero').waitFor();
 await page.locator('.mode-card[data-mode="random"]').click();
 await page.locator('.question-title').waitFor();
 assert.match(await page.locator('.dock-mid').innerText(),/1 \/ 60/,'random mode includes all 60');
 await page.locator('[data-act="next"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/2 \/ 60/);
 await page.locator('[data-act="go-practice"]').click();
 await page.locator('.practice-hero').waitFor();
 await page.locator('.practice-hero [data-act="open-all"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/41 \/ 60/,'random progress isolated from full bank');
 await page.locator('[data-act="go-practice"]').click();
 await page.locator('.practice-hero').waitFor();
 await page.locator('.mode-card[data-act="exam-intro"]').click();
 await page.locator('[data-act="start-exam"]').waitFor();
 await page.locator('[data-act="start-exam"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/1 \/ 30/);
 await page.locator('[data-act="exam-intro"]').click();
 await page.locator('[data-act="start-exam"]').waitFor();
 await page.locator('[data-act="start-exam"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/1 \/ 30/);
 await page.setViewportSize({width:1366,height:900});
 await page.goto(url,{waitUntil:'networkidle'});
 assert.equal(await page.locator('.app-header').isVisible(),true);
 await page.locator('.nav-item[href="#practice"]').click();
 await page.locator('details.numbers-wrap summary').waitFor();
 await page.locator('.practice-hero [data-act="open-all"]').click();
 assert.match(await page.locator('.dock-mid').innerText(),/41 \/ 60/);
 assert.deepEqual(errors,[]);
 console.log('PASS: mobile/desktop; 7 topics; 60 original questions; readable 16px options; fixed footer; correct grading; independent sessions; MCQ; exam 30; local persistence');
}finally{await browser.close()}
